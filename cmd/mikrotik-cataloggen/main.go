package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/Primexz/netops-mcp/internal/mikrotik/catalog"
	"github.com/Primexz/netops-mcp/internal/mikrotik/research"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	fetch := flag.Bool("fetch", false, "refresh ignored documentation cache and exit")
	specPath := flag.String("spec", "tools/mikrotik/catalog-spec.json", "reviewed resource and operation specification")
	cache := flag.String("cache", ".cache/mikrotik/manual", "downloaded documentation directory")
	flag.Parse()
	spec, err := research.LoadSpec(*specPath)
	if err != nil {
		return err
	}
	if *fetch {
		return research.Fetch(context.Background(), spec, *cache)
	}
	cat, err := research.Build(spec, *cache)
	if err != nil {
		return err
	}
	if err := preserveSourceTimes(cat.Sources, "docs/mikrotik/sources.json"); err != nil {
		return err
	}
	b, err := json.MarshalIndent(cat, "", "  ")
	if err != nil {
		return err
	}
	if err := research.WriteFile("internal/mikrotik/catalog/operations.json", append(b, '\n')); err != nil {
		return err
	}
	meta, err := json.MarshalIndent(cat.Sources, "", "  ")
	if err != nil {
		return err
	}
	if err := research.WriteFile("docs/mikrotik/sources.json", append(meta, '\n')); err != nil {
		return err
	}
	var report strings.Builder
	report.WriteString("# Operation coverage\n\nGenerated by `make catalog VENDOR=mikrotik`. All operations are documentation-derived and `live_verified=false`. No live router was connected.\n\n| Menu | Group | Operations |\n| --- | --- | --- |\n")
	for _, r := range spec.Resources {
		fmt.Fprintf(&report, "| `/%s` | %s | %s |\n", r.Path, r.Group, strings.Join(r.Actions, ", "))
	}
	fmt.Fprintf(&report, "\n%d MCP operation tools plus profile/catalog discovery tools. Tool schemas retain read-only properties for listing and omit them from mutation parameters.\n\n", len(cat.Operations))
	report.WriteString("Operations are an explicit allowlist, not a claim that every menu supports every REST method. Creation requirements and field omissions are reviewed overrides in `tools/mikrotik/catalog-spec.json`; each operation records applied override notes and its source URL. Firmware/package differences can make an operation unavailable. Firmware discovery is not a complete feature probe.\n\nNo unrestricted command execution, scripts, account management, lifecycle commands, backup/restore, packet capture, or continuous monitoring is exposed. Writes execute immediately, with no transaction or rollback and no automatic retries. Static-only tools refuse existing dynamic entries after a fresh read; concurrent changes by other administrators are still possible.\n")
	if err := research.WriteFile("docs/mikrotik/coverage.md", []byte(report.String())); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "generated %d operations from %d sources\n", len(cat.Operations), len(cat.Sources))
	return nil
}

// The ignored cache records the latest fetch. Identical content still belongs
// to the same published source snapshot and must not rewrite its retrieval date.
func preserveSourceTimes(sources []catalog.Source, path string) error {
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read published sources: %w", err)
	}
	var previous []catalog.Source
	if err := json.Unmarshal(b, &previous); err != nil {
		return fmt.Errorf("decode published sources: %w", err)
	}
	byURL := make(map[string]catalog.Source, len(previous))
	for _, source := range previous {
		byURL[source.URL] = source
	}
	for i, source := range sources {
		old, ok := byURL[source.URL]
		if ok && old.Version == source.Version && old.SHA256 == source.SHA256 && old.RetrievedAt != "" {
			sources[i].RetrievedAt = old.RetrievedAt
		}
	}
	return nil
}
